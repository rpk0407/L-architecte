// The atlas: the personas, the moments and the tensions, written out as Markdown for the people and the agents who read them.
//
// Generated from the same data the trials execute, so the documentation cannot drift from what the harness does. `npm run ux:atlas`
// writes the files; the unit tests regenerate them in memory and fail when the committed files are out of date.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { PERSONAS } from './index.mjs';
import { EVIDENCE } from './schema.mjs';
import { MOMENTS, momentById } from '../programme/moments.mjs';
import { TENSIONS } from '../programme/tensions.mjs';
import { CLOCKS, DEVICES, NETWORKS } from '../instruments/lib/surface.mjs';

const ROOT = resolve(new URL('../..', import.meta.url).pathname);
const BANNER = (what) => `<!-- Generated by \`npm run ux:atlas\` from ${what}. Do not edit by hand: change the data, then regenerate. -->\n`;
const pct = (w) => Math.round(w * 100) + '%';
const bullets = (xs) => xs.map((x) => `- ${x}`).join('\n');
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function persona(p) {
  const moments = p.moments.map((id) => `${id} ${momentById(id).fr}`).join(' · ');
  const scenes = p.scenes.map((s) => `| \`${s.id}\` | ${CLOCKS[s.clock].label} | ${DEVICES[s.device].label} | ${NETWORKS[s.network] ? NETWORKS[s.network].label : 'wifi'} | ${s.scheme} | ${s.trials.join(', ')} |`).join('\n');
  const intents = p.scenes.map((s) => `- \`${s.id}\`: ${s.label}. *${s.intent}.*`).join('\n');
  const ev = p.evidence.map((e) => `| ${e.cls} | ${cell(e.claim)} | ${cell(e.source || '')} | ${cell(e.validate)} |`).join('\n');
  return `### ${p.archetype} · ${p.name}, ${p.age}

*${p.role}* · ${p.kind} · **${p.priority}** · weight ${pct(p.weight)}

> ${p.headline}

${p.life}

**Why this weight.** ${p.why}
**Rhythm.** ${p.rhythm}
**His words.** says: ${p.says.map((x) => `“${x}”`).join(', ')} · avoids: ${p.avoids.map((x) => `“${x}”`).join(', ')}
**Budget (what the trials hold the product to).** ${p.budget.seconds} s · ${p.budget.taps} taps · ${p.budget.chars} characters
**Moments.** ${moments}

**Jobs to be done**
${bullets(p.jobs)}

**Fears**
${bullets(p.fears)}

**Delights**
${bullets(p.delights)}

**Success looks like.** ${p.success}
**Failure looks like.** ${p.failure}
**How to spot them in the salon’s data.** ${p.tells}

**Protect (never break for them)**
${bullets(p.protect)}

**Scenes the harness runs**

${intents}

| Scene | Moment | Device | Network | Scheme | Trials |
|---|---|---|---|---|---|
${scenes}

**Evidence**

| Class | Claim | Where it can be observed | How to validate |
|---|---|---|---|
${ev}
`;
}

export function renderPersonasMd() {
  const clients = PERSONAS.filter((p) => p.kind === 'client'), staff = PERSONAS.filter((p) => p.kind === 'staff');
  return `${BANNER('design/personas/*.mjs')}# The atlas of personas

${PERSONAS.length} people (${clients.length} clients, ${staff.length} staff), fictional composites built from the shop’s own product and the trade’s common knowledge. They are **hypotheses**: the independent research on barber-shop UX is thin and most of what is published comes from software vendors, so every claim below carries the class of its evidence and a way to test it on the salon’s own journal. The weights add up to 1 within each side and feed the persona view of the score; replace them with the shares you measure.

## How we know what we claim

| Class | Meaning |
|---|---|
${Object.entries(EVIDENCE).map(([k, v]) => `| **${k}** | ${v} |`).join('\n')}

## At a glance

| Persona | Who | Priority | Weight | Scenes |
|---|---|---|---|---|
${PERSONAS.map((p) => `| **${p.archetype}** | ${p.name}, ${p.age}, ${p.role} | ${p.priority} | ${pct(p.weight)} | ${p.scenes.map((s) => '`' + s.id + '`').join(', ')} |`).join('\n')}

## Clients

${clients.map(persona).join('\n')}
## Staff

${staff.map(persona).join('\n')}`;
}

export function renderMomentsMd() {
  return `${BANNER('design/programme/moments.mjs')}# The moments of truth

The spine every journey is hung on. A moment is where a person decides whether to trust, continue or leave: each has the question they are silently asking, the promise the product must keep, how it fails, and the trials that probe it.

| Id | Moment | Side | The question | The promise | How it fails | Surface | Trials |
|---|---|---|---|---|---|---|---|
${MOMENTS.map((m) => `| ${m.id} | **${m.fr}** (${m.en}) | ${m.side} | ${cell(m.question)} | ${cell(m.promise)} | ${cell(m.failure)} | ${cell(m.surface)} | ${m.trials.join(', ')} |`).join('\n')}

## Who walks through which moment

| Moment | ${PERSONAS.map((p) => p.archetype).join(' | ')} |
|---|${PERSONAS.map(() => '---').join('|')}|
${MOMENTS.map((m) => `| ${m.id} ${m.fr} | ${PERSONAS.map((p) => (p.moments.includes(m.id) ? '●' : '')).join(' | ')} |`).join('\n')}
`;
}

export function renderTensionsMd() {
  return `${BANNER('design/programme/tensions.mjs')}# The tensions

Where two good things pull against each other. Each tension names its two sides, the checks that make it visible in a run, and the Cabinet’s default ruling: a recommendation for the owner to take or leave, never a verdict. Tensions marked **owner’s decision** are not design questions.

${TENSIONS.map((t) => `## ${t.id} · ${t.fr} (${t.en})${t.ownerDecision ? ' · owner’s decision' : ''}

- **Side A.** ${t.sides[0]}
- **Side B.** ${t.sides[1]}

${t.story}

**Checks.** ${t.checks.length ? t.checks.map((c) => '`' + c + '`').join(', ') : 'none: judged by the panel.'}

**Default ruling.** ${t.ruling}
`).join('\n')}`;
}

export const FILES = {
  'design/programme/01-personas.md': renderPersonasMd,
  'design/programme/02-moments.md': renderMomentsMd,
  'design/programme/03-tensions.md': renderTensionsMd
};

/** Write the atlas, or (check: true) return the files that are out of date. */
export function writeAtlas({ check = false } = {}) {
  const stale = [];
  for (const [rel, render] of Object.entries(FILES)) {
    const path = join(ROOT, rel);
    const next = render();
    const now = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (check) { if (now !== next) stale.push(rel); } else if (now !== next) { writeFileSync(path, next); stale.push(rel); }
  }
  return stale;
}
